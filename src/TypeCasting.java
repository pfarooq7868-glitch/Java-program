public class TypeCasting {
    static void main() {
        int a=10;
        double b=a;
        System.out.println("a=" +a);
        System.out.println("b =" +b);

        double x=10.75;
        int y=(int)x;
        System.out.println("x =" +x);
        System.out.println("y ="+y);

        System.out.println("Farooq Khan");
    }
}
