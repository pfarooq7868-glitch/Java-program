package Taskoperators;

public class RelationalOperators {
    public static void main(String[]args){
        int a=10;
        int b=10;
        System.out.println(a==b);
        int x=10;
        int y=20;
        System.out.println(x!=y);
        int num=10;
        int num1=5;
        System.out.println(num>num1);
        int num2=40;
        int num3=55;
        System.out.println(num2<num3);
        int age=20;
        System.out.println(age>=18);
        int marks=45;
        System.out.println(marks>35);
        int num4=100;
        System.out.println(num4>=100);
        int num5=45;
        System.out.println(num5<=50);
        int storedPassword=1234;
        int enterPassword=1234;
        System.out.println(storedPassword==enterPassword);
        int height=140;
        System.out.println(height>150);
    }
}
