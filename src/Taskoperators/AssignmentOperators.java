        System.out.println("Number="+number);
        int number1=10;
        number1+=10;
        System.out.println("Result="+number1);
        int number2=25;
        number2-=5;
        System.out.println("Result="+number2);
        int number3=25;
        number3*=2;
        System.out.println("Result="+number3);
        int number4=50;
        number4/=2;
        System.out.println("Result="+number4);
        int number5=20;
        number5%=3;
        System.out.println("Remainder="+number5);
